function norm(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"']/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function parseCities(raw) {
  const cities = [];
  const seen = new Set();
  for (const line of raw.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.endsWith('already') || trimmed.endsWith('done')) continue;
    const parts = trimmed.split(/\s+/);
    const lon = Number(parts.pop());
    const lat = Number(parts.pop());
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
    const names = parts.join(' ').split('|').map((name) => name.trim()).filter(Boolean);
    const name = names[0];
    const key = norm(name);
    if (seen.has(key)) continue;
    seen.add(key);
    cities.push({ name, aliases: names.slice(1), lat, lon });
  }
  return cities;
}

export const RUSSIAN_CITIES = parseCities(RAW);

const POPULAR = [
  'Москва', 'Санкт-Петербург', 'Казань', 'Новосибирск',
  'Екатеринбург', 'Краснодар', 'Калининград', 'Владивосток'
];

export function popularCities() {
  return POPULAR.map((name) => RUSSIAN_CITIES.find((city) => city.name === name)).filter(Boolean);
}

export function cityNames() {
  return RUSSIAN_CITIES.map((city) => city.name);
}

function phraseIn(text, phrase) {
  let from = 0;
  while (from <= text.length) {
    const index = text.indexOf(phrase, from);
    if (index < 0) return false;
    const before = index === 0 || !/[a-zа-я]/i.test(text[index - 1]);
    const end = index + phrase.length;
    const after = end === text.length || !/[a-zа-я]/i.test(text[end]);
    if (before && after) return true;
    from = index + 1;
  }
  return false;
}

function labels(city) {
  return [city.name, ...city.aliases];
}

export function searchCities(query, limit = 8) {
  const q = norm(query);
  if (!q) return popularCities().slice(0, limit);
  const scored = [];
  for (const city of RUSSIAN_CITIES) {
    const names = labels(city).map(norm);
    if (names.some((name) => name === q)) scored.push([0, city]);
    else if (names.some((name) => name.startsWith(q))) scored.push([1, city]);
    else if (names.some((name) => name.includes(q))) scored.push([2, city]);
  }
  scored.sort((a, b) => a[0] - b[0] || a[1].name.localeCompare(b[1].name, 'ru'));
  const unique = [];
  for (const [, city] of scored) {
    if (!unique.includes(city)) unique.push(city);
    if (unique.length >= limit) break;
  }
  return unique;
}

export function interpretCity(text) {
  const q = String(text || '').trim();
  if (!q || q === '-' || q === '—') return { ok: true, city: null };
  const hits = searchCities(q, 8);
  if (!hits.length) {
    return { ok: false, error: 'Такого города нет в списке городов России. Напишите название, например Казань.' };
  }
  const n = norm(q);
  const exact = hits.find((city) => labels(city).some((name) => norm(name) === n));
  if (exact || hits.length === 1) return { ok: true, city: exact || hits[0] };
  return { ok: false, choices: hits, error: 'Уточните город.' };
}

export function cityInText(text) {
  const n = norm(text);
  if (!n) return null;
  let best = null;
  let bestLength = 0;
  for (const city of RUSSIAN_CITIES) {
    for (const label of labels(city)) {
      const phrase = norm(label);
      if (phrase.length > bestLength && phraseIn(n, phrase)) {
        best = city;
        bestLength = phrase.length;
      }
    }
  }
  return best;
}

export function distanceKm(a, b) {
  if (!a || !b) return null;
  const toRad = (deg) => deg * Math.PI / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLon = toRad(b.lon - a.lon);
  const lat1 = toRad(a.lat);
  const lat2 = toRad(b.lat);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.min(1, Math.sqrt(h)));
}

export function locate(text) {
  return cityInText(text) || interpretCity(text).city || null;
}

export function formatDistance(km, origin, place) {
  if (!origin) return '';
  if (!place || km == null) return 'Удалённость: город не распознан';
  if (origin.name === place.name || km < 1) return `Удалённость: ${place.name}`;
  const rounded = km < 10 ? km.toFixed(1) : String(Math.round(km));
  return `Удалённость: ${rounded} км от «${origin.name}»`;
}

export function withDistance(item, placeText, originText) {
  const origin = locate(originText);
  const place = locate(placeText);
  const km = origin && place ? distanceKm(origin, place) : null;
  return {
    ...item,
    distance_km: km == null ? null : Math.round(km * 10) / 10,
    distance_label: formatDistance(km, origin, place)
  };
}
